import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { memoryIdentity } from './identity-fixture.js';
import { newPasswordError } from '../../public/js/password-policy.js';
import passwordHash from '../../src/lib/password-hash.cjs';

let clock = Date.now();
let revoked = [];
const { db, identity } = memoryIdentity({ clock: () => clock, onRevoke: id => revoked.push(id) });
const legacy = memoryIdentity({ legacyDatabase: true });
const failed = memoryIdentity();
const password = crypto.randomBytes(24).toString('base64');
try {
  for (const unit of ['a', '中', '😀', ' ']) {
    for (const size of [11, 12, 128, 129]) assert.equal(Boolean(newPasswordError(unit.repeat(size))), size < 12 || size > 128);
  }
  assert(newPasswordError('\ud800'.repeat(12)));
  const padded = '  ' + '中😀'.repeat(6) + '  ';
  const admin = identity.bootstrap({ username: 'Admin', password: padded });
  assert.match(admin.id, /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/);
  assert.equal(admin.role_key, 'admin');
  assert.equal(identity.login('admin', padded).user.id, admin.id);
  assert.equal(identity.login('admin', padded.trim()), null, 'Passwords must not be trimmed');
  assert.equal(identity.login('missing', padded), null);
  assert.equal(identity.login('admin', 'wrong'), null);
  assert.throws(() => identity.bootstrap({ username: 'another', password }), /已初始化/);
  const editor = identity.createUser(admin.id, { username: 'Editor', password, role_key: 'editor' });
  const viewer = identity.createUser(admin.id, { username: 'Viewer', password, role_key: 'viewer' });
  assert.throws(() => identity.createUser(viewer.id, { username: 'forbidden', password, role_key: 'admin' }), /仅管理员/);
  assert.throws(() => identity.createUser(admin.id, { username: 'EDITOR', password, role_key: 'viewer' }), /已存在/);
  const login = identity.login('editor', password, 'real-request-id');
  const sessionRow = db.prepare('SELECT * FROM user_sessions WHERE user_id=?').get(editor.id);
  assert.notEqual(sessionRow.token_hash, login.token);
  assert.equal(sessionRow.token_hash, crypto.createHash('sha256').update(login.token).digest('hex'));
  assert.equal(identity.session(login.token).user.id, editor.id);
  clock += 2 * 86400000;
  assert.equal(identity.session(login.token, { renew: true }).renewed, true);
  assert.equal(identity.session(login.token, { renew: true }).renewed, false);
  clock += 31 * 86400000;
  assert.equal(identity.session(login.token), null);
  const currentLogin = identity.login('editor', password);
  const changed = identity.changeUser(admin.id, editor.id, { version: editor.version, active: false });
  assert.equal(changed.id, editor.id); assert.equal(changed.version, 2);
  assert.equal(identity.session(currentLogin.token), null);
  assert.equal(identity.login('editor', password), null);
  assert.deepEqual(revoked, [editor.id]);
  assert.throws(() => identity.changeUser(admin.id, editor.id, { version: 1, active: true }), /刷新/);
  identity.changeUser(admin.id, editor.id, { version: 2, active: true, role_key: 'viewer' });
  const oldToken = identity.login('editor', password).token;
  const latest = identity.getUser(editor.id);
  identity.changeUser(admin.id, editor.id, { version: latest.version, password: padded });
  assert.equal(identity.session(oldToken), null); assert.equal(identity.login('editor', password), null);
  const self = identity.getUser(editor.id);
  assert.throws(() => identity.changeUser(editor.id, editor.id, { version: self.version, old_password: 'wrong', password }, { selfPassword: true }), /原密码/);
  identity.changeUser(editor.id, editor.id, { version: self.version, old_password: padded, password }, { selfPassword: true });
  assert.equal(identity.login('editor', password).user.id, editor.id);
  assert.throws(() => identity.changeUser(admin.id, admin.id, { version: admin.version, active: false }), /至少一名/);
  const secondAdmin = identity.createUser(admin.id, { username: 'SecondAdmin', password, role_key: 'admin' });
  identity.changeUser(admin.id, admin.id, { version: admin.version, role_key: 'editor' });
  assert.throws(() => identity.changeUser(secondAdmin.id, secondAdmin.id, { version: 1, active: false }), /至少一名/);
  const before = identity.getUser(viewer.id);
  const tokenBefore = identity.login('viewer', password).token;
  db.exec("CREATE TEMP TRIGGER injected_audit_failure BEFORE INSERT ON audit_log BEGIN SELECT RAISE(ABORT,'injected-audit-failure'); END;");
  assert.throws(() => identity.changeUser(secondAdmin.id, viewer.id, { version: before.version, password: padded }), /injected-audit-failure/);
  assert.deepEqual(identity.getUser(viewer.id), before);
  assert(identity.session(tokenBefore), 'Rollback must preserve preexisting sessions');
  assert.throws(() => identity.createUser(secondAdmin.id, { username: 'must-rollback', password, role_key: 'viewer' }), /injected-audit-failure/);
  assert.equal(db.prepare("SELECT 1 FROM users WHERE username='must-rollback'").get(), undefined);
  db.exec('DROP TRIGGER injected_audit_failure');
  const audit = db.prepare("SELECT * FROM audit_log WHERE action='identity.password-reset' ORDER BY id DESC LIMIT 1").get();
  assert.equal(audit.actor_user_id, admin.id); assert.equal(audit.target_user_id, editor.id);
  const serialized = JSON.stringify(db.prepare('SELECT * FROM audit_log').all());
  assert(!serialized.includes(password)); assert(!serialized.includes(padded)); assert(!serialized.includes(tokenBefore));
  assert(!JSON.stringify(identity.listUsers(secondAdmin.id)).includes('password_hash'));
  assert(!JSON.stringify(identity.listUsers(secondAdmin.id)).includes('token_hash'));
  const oldPassword = '短旧密码';
  const salt = crypto.randomBytes(16).toString('hex');
  const oldHash = salt + ':' + crypto.scryptSync(oldPassword, salt, 32).toString('hex');
  assert(passwordHash.verifyPassword(oldPassword, oldHash));
  assert.throws(() => legacy.identity.bootstrap({ username: 'takeover', password }), /原账号凭据/);
  assert.throws(() => legacy.identity.bootstrap({ old_password: 'wrong', confirm_legacy: true }, { legacy: { user: 'Legacy', passHash: oldHash } }), /原账号凭据/);
  const migrated = legacy.identity.bootstrap({ old_password: oldPassword, confirm_legacy: true }, { legacy: { user: 'Legacy', passHash: oldHash } });
  assert.equal(legacy.identity.login('legacy', oldPassword).user.id, migrated.id);
  failed.db.exec("CREATE TEMP TRIGGER fail_first_audit BEFORE INSERT ON audit_log BEGIN SELECT RAISE(ABORT,'first-audit-failure'); END;");
  assert.throws(() => failed.identity.bootstrap({ username: 'First', password }), /first-audit-failure/);
  assert.equal(failed.db.prepare('SELECT count(*) AS n FROM users').get().n, 0);
  assert.equal(failed.identity.state().initialized, 0);
  const staleActorVersion = identity.getUser(secondAdmin.id).session_version;
  db.prepare('UPDATE users SET session_version=session_version+1 WHERE id=?').run(secondAdmin.id);
  assert.throws(() => identity.createUser(secondAdmin.id, { username: 'revokedActor', password, role_key: 'viewer' }, 'stale-request',
    { actorSessionVersion: staleActorVersion }), /登录已失效/, 'Transaction must recheck the authenticating session version');
  assert.throws(() => identity.listUsers(secondAdmin.id, staleActorVersion), /登录已失效/);
  console.log('identity service: Unicode password boundaries, migration, sessions, revocation, last admin and transactional audit rollback passed');
} finally { db.close(); legacy.db.close(); failed.db.close(); }
